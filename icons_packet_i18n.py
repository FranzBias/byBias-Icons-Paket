_current_lang = "en"


def set_language(code):
    global _current_lang
    if code in {c for c, _n, _f in LANGUAGES}:
        _current_lang = code


def get_language():
    return _current_lang


def set_language_from_locale():
    """Use the system language (LANGUAGE, LC_ALL, LC_MESSAGES, LANG) when it is
    one of LANGUAGES; otherwise keep English. Returns the language in use."""
    import os
    for var in ("LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG"):
        value = os.environ.get(var)
        if value:
            set_language(value.split(":")[0][:2].lower())
            break
    return _current_lang


def tr(text):
    """Translate `text` (an English source string) to the current language.
    Falls back to the English source if no translation exists."""
    table = CATALOG.get(_current_lang)
    if not table:
        return text
    return table.get(text, text)


